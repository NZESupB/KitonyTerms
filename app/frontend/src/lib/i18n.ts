export type TextKey = keyof typeof english;
export type TextValues = Readonly<Record<string, string | number>>;
export function translate(
  language: string,
  key: TextKey,
  values: TextValues = {},
): string {
  const source = language === "english" ? english[key] : key;
  return source.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name)
      ? String(values[name])
      : match,
  );
}
